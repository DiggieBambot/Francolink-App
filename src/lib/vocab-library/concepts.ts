const BY_ALIAS = new Map<string, Concept>();
for (const c of CONCEPTS) {
  BY_ALIAS.set(c.slug, c);
  for (const a of c.aliases) BY_ALIAS.set(a, c);
}

/**
 * Lowercase, strip accents and punctuation, and drop a leading article so
 * "An Onion" and "onion" are the same key. Articles only — "to read" keeps its
 * "to", because the infinitive is how the courses label actions.
 */
function normalize(s: string): string {
  return String(s || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z ]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/^(a|an|the) /, "");
}

/**
 * Resolve an English hint (image_query or translation) to a library concept.
 *
 * Matching is deliberately EXACT — whole-hint against a slug or a listed alias.
 * A word-level fallback looks tempting ("a knee bending in sport" -> knee) but
 * misfires badly on the wider corpus: "shaking hands" in a B1 business lesson
 * became the cartoon child's hand, and "jouer au foot" became a foot. Adding
 * an alias is cheap; a wrong picture in a lesson is not.
 *
 * Hints are tried in order, so callers should pass the most specific first —
 * image_query before translation. That is what keeps "orange fruit" on the
 * fruit and a bare "orange" on the colour swatch.
 */
export function conceptFor(...hints: (string | undefined)[]): Concept | null {
  for (const hint of hints) {
    const n = normalize(hint || "");
    if (!n) continue;
    const hit = BY_ALIAS.get(n);
    if (hit) return hit;
  }
  return null;
}

export function conceptBySlug(slug: string): Concept | null {
  return CONCEPTS.find((c) => c.slug === slug) || null;
}
