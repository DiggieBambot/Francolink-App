// src/lib/vocab-library/concepts.ts
//
// The shared vocab picture library: one illustration per ENGLISH concept,
// reused by every language course and by the kids' games. Keying on the
// concept (not "le genou" / "la rodilla" / "das Knie") means one picture is
// generated once and every course points at it.
//
// Why it exists: lesson images used to come from Pexels stock photos, and a
// photo search for "knee" returns a whole footballer. Children need to see the
// one thing they are naming, so these are flat cartoon illustrations built to
// be unambiguous.
//
// Four kinds, each chosen for precision rather than convenience:
//   - "figure"  a part of the shared cartoon child, marked with a highlight
//               ring and cropped around it. A body part can't be shown alone —
//               a cropped hand and arm look identical.
//   - "object"  a standalone single-subject flat illustration (FLUX).
//   - "shape"   drawn with canvas. A model renders "diamond" as a gemstone.
//   - "numeral" drawn with canvas. Image models garble digits.
//   - `from`    an object whose picture already exists as a hand-verified game
//               tile in public/games/<theme>/ — copied in, never regenerated.
//
// Images live in Supabase Storage at lesson-images/vocab-library/<slug>.png.
// Generated and uploaded by scripts/generate-vocab-library.mjs.

export type Annotate = { x: number; y: number; size: number };

export interface Concept {
  /** Stable library key and filename. */
  slug: string;
  /** English label, shown in tooling. */
  label: string;
  kind: "figure" | "object" | "shape" | "numeral";
  /** Ring placement on the base figure, normalized 0-1. "figure" only. */
  annotate?: Annotate;
  /** Crop half-extent around the ring, normalized. "figure" only. */
  zoom?: number;
  /** FLUX prompt subject. "object" only, unless `from` is set. */
  prompt?: string;
  /** Copy an already-verified game tile instead of generating. */
  from?: { theme: string; slug: string };
  /** Which shape to draw. "shape" only. */
  shape?: string;
  /** Which number to draw. "numeral" only. */
  numeral?: number;
  /**
   * Set when a generated picture failed review — wrong subject, or text baked
   * into the image. Held concepts are never served to a lesson; regenerate
   * with `--force --only=<slug>` and clear the flag once the picture is good.
   */
  hold?: string;
  /** English phrasings that should resolve to this concept (lowercase). */
  aliases: string[];
}

